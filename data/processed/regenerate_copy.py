import json
import re
from pathlib import Path
from scripts.audit import conclusion

r = json.loads(Path('frontend/audit.json').read_text(encoding='utf-8'))
assert r['status'] == 'FROZEN - repo pipeline'
rows = r['presets']
p1, p2, p3 = rows
mapping = {
    '452.5': f"{p1['change_W_pct']:.1f}", '5.4': f"{p1['change_U_pct']:.1f}",
    '447.1': f"{p1['diff_pp']:.1f}", '97.7': f"{p2['change_W_pct']:.1f}",
    '11.2': f"{p2['change_U_pct']:.1f}", '86.5': f"{p2['diff_pp']:.1f}",
    '86.6': f"{p2['diff_pp']:.1f}", '20.5': f"{abs(p3['change_W_pct']):.1f}",
}
for name in ['README.md', 'docs/AUDIT_SPEC.md', 'docs/BUILD_BRIEF.md', 'docs/COPY_PACK.md']:
    p = Path(name)
    s = p.read_text(encoding='utf-8')
    s = re.sub('|'.join(re.escape(k) for k in mapping), lambda m: mapping[m.group()], s)
    p.write_text(s, encoding='utf-8')

p = Path('docs/AUDIT_SPEC.md')
s = p.read_text(encoding='utf-8')
a, b = s.index('## The three preset comparisons'), s.index('Gate 6')
section = '''## The three preset comparisons (FROZEN - repo pipeline)

Canonical values are generated by scripts/audit.py and frozen in frontend/audit.json.
The original VM reference is retained independently in scripts/audit.py for validation.
Gate: W/U totals and W/U ratios within 1.5% relative; C = W - U exactly and
its reference deviation <=1.5% of that period's repo W (BUILD_BRIEF section 1).

'''
for i, row in enumerate(rows, 1):
    section += f"P{i} {row['id']} - {row['a']} vs {row['b']}:\n  W: {row['W_a']:,} -> {row['W_b']:,} ({row['change_W_pct']:+.1f}%)\n  U: {row['U_a']:,} -> {row['U_b']:,} ({row['change_U_pct']:+.1f}%)\n  C: {row['C_a']:,} -> {row['C_b']:,}; difference {row['diff_pp']:.1f} pp.\n\n"
section += '''P3 is the within-season interruption case: S-NPP is in both seasonal
fleets, so C is zero and the seasonal decomposition cannot expose the
interruption; S-NPP detections end on 2 Nov and are zero from 3 Nov.

'''
s = s[:a] + section + s[b:]
p.write_text(s, encoding='utf-8')

p = Path('docs/BUILD_BRIEF.md')
s = p.read_text(encoding='utf-8')
a, b = s.index('## 1.'), s.index('## 2.')
s = s[:a] + '''## 1. Data - frozen repo values and calibrated validation gate

- The app reads ONE file: frontend/audit.json, schema "audit-app v1";
  status "FROZEN - repo pipeline". The repo pipeline is canonical.
- Compare to the pinned original VM reference, never to previous generated output.
- W and U are measured quantities: each total must be within 1.5% relative.
- Ratios W_b/W_a and U_b/U_a must each be within 1.5% relative.
- C is derived: verify C = W - U exactly per period, and
  |C_repo - C_ref| <= 1.5% of that period's repo W.
- Percentage-point tolerances are superseded: they mis-scale for large ratios.
  Arlo accepted the 2026-11-15 amplification case: P1 totals +0.44/+0.93%,
  W ratio +0.48%, change +2.66 pp. P2 C_b differs by 752, 0.70% of repo W_b.
- Freeze all app data together; record values, acceptance lines and the frozen
  commit SHA in BUILD_PROGRESS.md. All dependent number strings come from the
  frozen file and must change everywhere or nowhere.

''' + s[b:]
a, b = s.index('## 4.'), s.index('## 5.')
section = '''## 4. Conclusion lines - frozen acceptance tests

Compute percentage changes and diff_pp from unrounded integer counts, then
round only for display. Build shared_label from the preset's shared satellites
using Terra / Aqua / Suomi NPP / NOAA-20 joined by "+".
The following lines are rendered from frontend/audit.json and locked verbatim:

'''
for i, row in enumerate(rows, 1):
    section += f'P{i}: "{conclusion(row)}"\n\n'
s = s[:a] + section + s[b:]
p.write_text(s, encoding='utf-8')

p = Path('docs/COPY_PACK.md')
s = p.read_text(encoding='utf-8')
s = s.replace('All numbers below come from the frozen preset values supplied for review.',
              'All numbers below come from the canonical frozen frontend/audit.json.')
s = s.replace('{w}%; Terra+Aqua, {u}%', '{w}%; {shared_label}, {u}%')
a = s.index('"Recorded change', s.index('### 4c.'))
b = s.index('### 4d.', a)
s = s[:a] + '"' + conclusion(p3) + '"\n\n' + s[b:]
a = s.index('```json') + len('```json')
b = s.index('```', a)
copy = json.loads(s[a:b])
copy['conclusion_templates']['interruption'] = conclusion(p3)
s = s[:a] + '\n' + json.dumps(copy, ensure_ascii=False, indent=2) + '\n' + s[b:]
p.write_text(s, encoding='utf-8')
Path('data/processed/frozen_acceptance_lines.json').write_text(
    json.dumps({row['id']: conclusion(row) for row in rows}, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
print('Regenerated all four canonical copy files and acceptance lines.')
